function buildFallbackSeo(product: Product): ProductSeoEntry {
  const title = product.title.trim();
  const gameTitle = product.game?.title;
  const gameTitleEn = product.game?.titleEn;
  const categoryName = product.category?.name || 'محصولات گیمینگ';

  const existingDesc = (product.description || '').trim();
  const intro =
    existingDesc ||
    `${title} یکی از محصولات دسته ${categoryName}${gameTitle ? ` در بازی ${gameTitle}` : ''} است که با پرداخت ریالی، تحویل سریع و پشتیبانی ۲۴ ساعته در فروشگاه تایتان عرضه می‌شود.`;

  const hasWhatIsSection = existingDesc.includes('چیست؟') || existingDesc.includes('## ');

  const structuredDescription = hasWhatIsSection
    ? existingDesc
    : `${intro}

## ${title} چیست؟
${title}${gameTitle ? ` از آیتم‌ها و خدمات مرتبط با ${gameTitle}${gameTitleEn ? ` (${gameTitleEn})` : ''}` : ` یکی از محصولات بخش ${categoryName}`} است که به گیمرها امکان می‌دهد به امکانات و اعتبار درون‌بازی دسترسی داشته باشند.

## مزایا و ویژگی‌های خرید ${title}
- تحویل سریع مطابق زمان‌بندی اعلام‌شده در مشخصات محصول
- پرداخت ریالی از درگاه بانکی و پیگیری لحظه‌ای سفارش در پنل کاربری
- پشتیبانی ۲۴ ساعته کارشناسان تایتان از لحظه ثبت سفارش تا فعال‌سازی کامل`;

  const baseKeywords = [
    title,
    `خرید ${title}`,
    `قیمت ${title}`,
    ...(gameTitle ? [gameTitle, `خرید آیتم ${gameTitle}`] : []),
    ...(gameTitleEn ? [`${gameTitleEn}`] : []),
    categoryName,
  ];

  return {
    subtitle: product.subtitle || `خرید ${title} با تحویل سریع و پشتیبانی ۲۴ ساعته از فروشگاه تایتان`,
    description: structuredDescription,
    keywords: Array.from(new Set(baseKeywords)),
    tags:
      product.tags && product.tags.length > 0
        ? product.tags
        : ['تحویل سریع', 'پشتیبانی ۲۴ ساعته', 'پیگیری آنلاین سفارش', 'پرداخت امن ریالی'],
    metaTitle: product.metaTitle || `خرید ${title} با تحویل سریع | فروشگاه تایتان`,
    metaDescription:
      product.metaDescription ||
      `خرید ${title} با قیمت روز، تحویل سریع، پیگیری سفارش و پشتیبانی ۲۴ ساعته در فروشگاه تایتان.`,
    imageAlt: product.imageAlt || `خرید ${title} از فروشگاه تایتان`,
  };
}

/**
 * Returns the deduplicated SEO keyword list for a product, combining backend
 * `specs.keywords` (if set in Django Admin) with our curated SEO dictionary.
 */
export function getProductKeywords(product: Product): string[] {
  const entry = PRODUCT_SEO_CONTENT[product.slug] ?? buildFallbackSeo(product);
  const fromSpecs = product.specs?.keywords
    ? String(product.specs.keywords)
        .split(/[،,]+/)
        .map(k => k.trim())
        .filter(Boolean)
    : [];
  return Array.from(new Set([...fromSpecs, ...entry.keywords]));
}

/**
 * Enriches a `Product` with structured SEO description (including "چیست؟" headings
 * and bullet points), tags, subtitle, FAQs, and meta tags if missing or incomplete.
 */
export function enrichProductSeo(product: Product): Product {
  const entry = PRODUCT_SEO_CONTENT[product.slug] ?? buildFallbackSeo(product);
  const currentDesc = (product.description || '').trim();
  const hasRichStructure = currentDesc.includes('## ') || currentDesc.includes('چیست؟');

  const description = entry.overrideBackend || !hasRichStructure ? entry.description : currentDesc;

  return {
    ...product,
    title: entry.overrideBackend && entry.title ? entry.title : product.title,
    subtitle: entry.overrideBackend ? entry.subtitle || product.subtitle : product.subtitle || entry.subtitle || '',
    description,
    tags: entry.overrideBackend ? entry.tags : product.tags && product.tags.length > 0 ? product.tags : entry.tags,
    metaTitle: entry.overrideBackend ? entry.metaTitle : product.metaTitle || entry.metaTitle,
    metaDescription: entry.overrideBackend ? entry.metaDescription : product.metaDescription || entry.metaDescription,
    imageAlt: entry.overrideBackend ? entry.imageAlt || product.title : product.imageAlt || entry.imageAlt || product.title,
    faqs: entry.faqs ?? product.faqs,
  };
}

/**
 * Parses a product description (supporting `## ` H2 headings, `### ` H3 subheadings, and `- ` bullet lists)
 * into clean semantic blocks for `#pd-about`.
 */
export function parseDescriptionBlocks(description: string): DescriptionBlock[] {
  const lines = (description || '')
    .split(/\r?\n/)
    .map(l => l.trim())
    .filter(Boolean);

  const blocks: DescriptionBlock[] = [];
  let currentList: string[] = [];

  const flushList = () => {
    if (currentList.length > 0) {
      blocks.push({ type: 'list', items: currentList });
      currentList = [];
    }
  };

  for (const line of lines) {
    if (line.startsWith('### ')) {
      flushList();
      blocks.push({ type: 'subheading', text: line.slice(4).trim() });
    } else if (line.startsWith('## ')) {
      flushList();
      blocks.push({ type: 'heading', text: line.slice(3).trim() });
    } else if (line.startsWith('- ') || line.startsWith('• ')) {
      currentList.push(line.slice(2).trim());
    } else {
      flushList();
      blocks.push({ type: 'paragraph', text: line });
    }
  }

  flushList();
  return blocks;
}

/**
 * Strips markdown markers (`## `, `### `, `- `, `[text](url)`) for plain-text contexts like JSON-LD schema
 * or fallback meta descriptions.
 */
export function plainTextDescription(description: string): string {
  return (description || '')
    .replace(/^###?\s+/gm, '')
    .replace(/^[-•]\s+/gm, '')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}
